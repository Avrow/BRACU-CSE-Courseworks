def calc_util(gene, target, weights):
    max_len = max(len(gene), len(target))
    score = 0

    for i in range(max_len):
        weight = weights[i] if i < len(weights) else 1
        gene_ascii = ord(gene[i]) if i < len(gene) else 0
        target_ascii = ord(target[i]) if i < len(target) else 0
        score += weight * abs(gene_ascii - target_ascii)

    return -score

def Boost(weights, pos, sid):
    first_digits = int(str(sid)[:2])
    multiplier = first_digits / 100

    boosted_weights = weights.copy()
    for i in range(pos, len(boosted_weights)):
        boosted_weights[i] *= multiplier

    return boosted_weights

def solve(pool, target, weights, current="", agent1_turn=True, sid=None):
    if not pool:
        return calc_util(current, target, weights), current

    if agent1_turn:
        best_score = float('-inf')
        best_gene = ""

        for nucleotide in pool:
            new_pool = pool.copy()
            new_pool.remove(nucleotide)
            new_gene = current + nucleotide

            current_weights = weights
            if nucleotide == 'S' and sid is not None:
                s_pos = len(current)
                current_weights = Boost(weights, s_pos, sid)

            score, gene = solve(new_pool, target, current_weights, new_gene, False, sid)

            if score > best_score:
                best_score = score
                best_gene = gene

        return best_score, best_gene

    else:
        best_score = float('inf')
        best_gene = ""

        for nucleotide in pool:
            new_pool = pool.copy()
            new_pool.remove(nucleotide)
            new_gene = current + nucleotide

            score, gene = solve(new_pool, target, weights, new_gene, True, sid)

            if score < best_score:
                best_score = score
                best_gene = gene

        return best_score, best_gene

def process(pool_str, target, student_id):
    pool = pool_str.split(',')

    sid_str = str(student_id)
    length = len(target)
    weights = [int(digit) for digit in sid_str[-length:]]

    pool_without_s = [x for x in pool if x != 'S']
    score_no_s, gene_no_s = solve(pool_without_s, target, weights)

    has_s = 'S' in pool

    if has_s:
        score_s, gen_s = solve(pool, target, weights, sid=student_id)
        use_s = score_s > score_no_s
        return use_s, gen_s, score_s, gene_no_s, score_no_s
    else:
        return False, gene_no_s, score_no_s, gene_no_s, score_no_s

