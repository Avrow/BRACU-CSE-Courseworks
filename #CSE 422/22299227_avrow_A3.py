import math

class GeneSequencer:
    def __init__(self, pool, target, weights):
        self.pool = pool
        self.target = target
        self.weights = weights

    def evaluate(self, gene):
        score = 0
        gene_str = ''.join(gene)
        max_len = max(len(gene_str), len(self.target))
        for i in range(max_len):
            if i < len(gene_str):
                g = ord(gene_str[i])
            else:
                g = 0

            if i < len(self.target):
                t = ord(self.target[i])
            else:
                t = 0

            if i < len(self.weights):
                w = self.weights[i]
            else:
                w = 1
            score += w * abs(g - t)

        return -score

    def search(self):
        return self._minimax([], self.pool, True, -math.inf, math.inf)

    def _minimax(self, current, pool, is_max, alpha, beta):
        if not pool:
            return self.evaluate(current), current

        if is_max:
            max_eval = -math.inf
            best_gene = current
            for i in range(len(pool)):
                trial = current + [pool[i]]
                remaining = pool[:i] + pool[i+1:]
                val, gene_seq = self._minimax(trial, remaining, False, alpha, beta)
                if val > max_eval:
                    max_eval = val
                    best_gene = gene_seq
                alpha = max(alpha, val)
                if beta <= alpha:
                    break
            return max_eval, best_gene
        else:
            min_eval = math.inf
            best_gene = current
            for i in range(len(pool)):
                trial = current + [pool[i]]
                remaining = pool[:i] + pool[i+1:]
                val, gene_seq = self._minimax(trial, remaining, True, alpha, beta)
                if val < min_eval:
                    min_eval = val
                    best_gene = gene_seq
                beta = min(beta, val)
                if beta <= alpha:
                    break
            return min_eval, best_gene

