#task - 1
import random
import math

GRID_SIZE = 25

COMPONENTS = {
    'ALU': (5, 5),
    'Cache': (7, 4),
    'Control Unit': (4, 4),
    'Register File': (6, 6),
    'Decoder': (5, 3),
    'Floating Unit': (5, 5)
}

COMPONENT_NAMES = ['ALU', 'Cache', 'Control Unit', 'Register File', 'Decoder', 'Floating Unit']

CONNECTIONS = [
    (3, 0),
    (2, 0),
    (0, 1),
    (3, 5),
    (1, 4),
    (4, 5)
]

def genPopulation():
    population = []
    for i in range(6):
        chromosome = []
        for comp_name in COMPONENT_NAMES:
            width, height = COMPONENTS[comp_name]
            max_x = GRID_SIZE - width
            max_y = GRID_SIZE - height
            x = random.randint(0, max_x)
            y = random.randint(0, max_y)
            chromosome.append((x, y))
        population.append(chromosome)
    return population

def overlapings(chromosome):
    overlap_count = 0

    for i in range(len(chromosome)):
        for j in range(i + 1, len(chromosome)):
            comp1_name = COMPONENT_NAMES[i]
            comp2_name = COMPONENT_NAMES[j]

            x1, y1 = chromosome[i]
            x2, y2 = chromosome[j]

            w1, h1 = COMPONENTS[comp1_name]
            w2, h2 = COMPONENTS[comp2_name]

            A_left, A_right = x1, x1 + w1
            A_bottom, A_top = y1, y1 + h1
            B_left, B_right = x2, x2 + w2
            B_bottom, B_top = y2, y2 + h2

            overlap = not (A_right <= B_left or A_left >= B_right or A_bottom >= B_top or A_top <= B_bottom)

            if overlap:
                overlap_count += 1

    return overlap_count

def wireDist(chromosome):
    total_distance = 0.0

    for comp1_idx, comp2_idx in CONNECTIONS:
        x1, y1 = chromosome[comp1_idx]
        x2, y2 = chromosome[comp2_idx]

        w1, h1 = COMPONENTS[COMPONENT_NAMES[comp1_idx]]
        w2, h2 = COMPONENTS[COMPONENT_NAMES[comp2_idx]]

        center1_x = x1 + w1 / 2
        center1_y = y1 + h1 / 2
        center2_x = x2 + w2 / 2
        center2_y = y2 + h2 / 2

        distance = math.sqrt((center2_x - center1_x)**2 + (center2_y - center1_y)**2)
        total_distance += distance

    return total_distance

def boundingArea(chromosome):
    min_x = min_y = float('inf')
    max_x = max_y = float('-inf')

    for i, (x, y) in enumerate(chromosome):
        comp_name = COMPONENT_NAMES[i]
        width, height = COMPONENTS[comp_name]

        min_x = min(min_x, x)
        min_y = min(min_y, y)
        max_x = max(max_x, x + width)
        max_y = max(max_y, y + height)

    return (max_x - min_x) * (max_y - min_y)

def fitness(chromosome):

    ALPHA = 1000
    BETA = 2
    GAMMA = 1

    overlap_count = overlapings(chromosome)
    wiring_distance = wireDist(chromosome)
    bounding_area = boundingArea(chromosome)

    fitness = -(ALPHA * overlap_count + BETA * wiring_distance + GAMMA * bounding_area)

    return fitness

def randomPopulation(population):
    return random.choice(population)

def single_point_crossover(parent1, parent2):
    crossover_point = random.randint(1, len(parent1) - 1)

    child1 = parent1[:crossover_point] + parent2[crossover_point:]
    child2 = parent2[:crossover_point] + parent1[crossover_point:]

    return child1, child2

def mutation(chromosome):
    if random.random() < 0.12:
        comp_idx = random.randint(0, len(chromosome) - 1)
        comp_name = COMPONENT_NAMES[comp_idx]
        width, height = COMPONENTS[comp_name]

        max_x = GRID_SIZE - width
        max_y = GRID_SIZE - height
        new_x = random.randint(0, max_x)
        new_y = random.randint(0, max_y)

        mutated = chromosome.copy()
        mutated[comp_idx] = (new_x, new_y)
        return mutated

    return chromosome

def run_genetic_algorithm():
    population = genPopulation()

    topFitness = float('-inf')
    bestCromosome = None

    for generation in range(15):
        fitness_scores = [fitness(chrom) for chrom in population]

        best_idx = max(range(len(fitness_scores)), key=lambda i: fitness_scores[i])
        if fitness_scores[best_idx] > topFitness:
            topFitness = fitness_scores[best_idx]
            bestCromosome = population[best_idx].copy()

        new_population = []

        newIndexes = sorted(range(len(fitness_scores)), key=lambda i: fitness_scores[i], reverse=True)[:2]
        for idx in newIndexes:
            new_population.append(population[idx])

        while len(new_population) < 6:
            parent1 = randomPopulation(population)
            parent2 = randomPopulation(population)

            child1, child2 = single_point_crossover(parent1, parent2)

            child1 = mutation(child1)
            child2 = mutation(child2)

            new_population.extend([child1, child2])

        population = new_population[:6]

    best_overlap = overlapings(bestCromosome)
    best_wiring = wireDist(bestCromosome)
    best_area = boundingArea(bestCromosome)

    return {
        'bestCromosome': bestCromosome,
        'topFitness': topFitness,
        'overlap_count': best_overlap,
        'wiring_distance': best_wiring,
        'bounding_area': best_area
    }

def decodeChromosome(chromosome):
    placement = {}
    for i, (x, y) in enumerate(chromosome):
        comp_name = COMPONENT_NAMES[i]
        placement[comp_name] = (x, y)
    return placement

results = run_genetic_algorithm()
print(results)

